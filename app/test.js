const C = require("./calc.js");
const data = require("./plans.json");
const base = { use: "prototype", projects: 1, mau: 10, dbGb: 0.05, storageGb: 0.01, egressGb: 0.1, restore: "none", alwaysOn: false, sso: false, compliance: false, backupDays: 0, compute: "micro" };
let fail = 0;
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fail++; console.log(ok ? "ok  " : "FAIL", name, ok ? "" : JSON.stringify(got) + " != " + JSON.stringify(want)); };
eq("prototype stays free", C.recommend(base, data).level, "free");
eq("always-on -> pro", C.recommend({ ...base, alwaysOn: true }, data).level, "pro");
eq("exactly at free limit stays free", C.recommend({ ...base, mau: 50000, dbGb: 0.5, storageGb: 1, egressGb: 5, projects: 2 }, data).level, "free");
eq("one over MAU -> pro", C.recommend({ ...base, mau: 50001 }, data).level, "pro");
eq("3 projects -> pro", C.recommend({ ...base, projects: 3 }, data).level, "pro");
eq("customer-facing -> pro", C.recommend({ ...base, use: "customer" }, data).level, "pro");
eq("daily restore -> pro", C.recommend({ ...base, restore: "daily" }, data).level, "pro");
eq("sso -> team", C.recommend({ ...base, sso: true }, data).level, "team");
eq("14 day backups -> team", C.recommend({ ...base, backupDays: 14 }, data).level, "team");
eq("pro single micro = 25", C.cost("pro", { ...base, use: "customer" }, data).total, 25);
eq("pro two projects = 35", C.cost("pro", { ...base, projects: 2 }, data).total, 35);
eq("pro + pitr = 125", C.cost("pro", { ...base, restore: "pitr" }, data).total, 125);
eq("pro egress 350GB = 25+9", C.cost("pro", { ...base, egressGb: 350 }, data).total, 34);
eq("pro mau 120k = 25+65", C.cost("pro", { ...base, mau: 120000 }, data).total, 90);
eq("team base", C.cost("team", base, data).total, 599);
eq("free cost 0", C.cost("free", base, data).total, 0);
eq("stale after 60 days", C.isStale("2026-10-27", "2026-12-27"), true);
eq("fresh after 10 days", C.isStale("2026-10-27", "2026-11-06"), false);
process.exit(fail ? 1 : 0);
